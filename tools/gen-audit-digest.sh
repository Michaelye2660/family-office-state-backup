#!/usr/bin/env bash
# 🔴 治理时钟＝SGT
export TZ=Asia/Singapore
# ============================================================================
# 内审官报告 · DIGEST 抽取件生成器（`ADJ-0801-12⑤` 令立 · 2026-08-01 · SGT）
#
# 🔴 为哪次事故／哪条缺口而立（照本仓通则：每个器之文件头写明它自己为何而生）：
#   CGM 建议「只直报 §庚（强制回应清单）＋ §己（另捕节）约 4 KB，全文照旧落库备查」，GM 接受，
#   **惟其当场指出该建议物理上不可执行**：
#     「**GM 侧无范围读，只能整档取回——要本席『只读其中 4 KB』，物理上做不到。**」
#   **即：一个「你只读这一部分」的建议，在收件方无范围读的情况下，等于没提。**
#   **故本器把「只读一部分」由一句请求，变成一份真的只含那一部分的文件。**
#
# 🔴 GM 同轮登记之更大缺口（照录·本器只治其第四例，不治其族）：
#   此系「**一份被指定为 GM 应读之物，超出 GM 可读范围**」之**第四例**
#   （`-07⑦` 有界三节／`-08⑦` §五正文／`-10①` 样本框／本项）。
#   **本器不解决该族；全库清单见 `docs/gm-readability-inventory.md`（`-08⑦` 之回报）。**
#
# 🔴 它不核什么（先列不覆盖处·免「未报」被读作「已核无事」）：
#   - **不判抽取得够不够** —— 属判断类，归 GM 之维二；
#   - **不改一字**：§庚／§己 逐字整节搬运，**不概括、不补写、不重排**；
#   - **不判内审官之结论对错**，亦不替其降色；
#   - **不核正本是否忠于内审官所写**（`ADJ-0801-12③` 已明：blob SHA 相等只证两份一致，
#     **不证任一份忠于内审官所写**）。
#
# 🔴 抽取判据（预先写死·非逐案自选）：
#   自 `docs/internal-audit/YYYY-MM-DD-auditor.md` 取 **`### §庚`** 与 **`### §己`** 两整节
#   （自其标题行起，至下一个同级或更高级标题止），**逐字**。
#   **两节缺任一 → 本器不出件并报错**（**宁可不出，不可出一份看起来完整的半件**）。
#
# 🔴 死法与检出法（照 `cc-knowledge.md:261`·凡新增结构立时即写其退役条件）：
#   **退役条件**：当 GM 侧获得**范围读**（可只取一档之一节）→ 本器失去存在理由，得呈请退役。
#     **「一直没出错」不构成退役理由。**
#   **检出法（落在本器之外·不靠人记得）**：
#     `internal-audit.sh` **§二 乙4-b** 每日核「当日 `gm-inbox/AUDIT-*-DIGEST.md` 在否」——**缺件即 🔴**。
# ============================================================================
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1
. tools/_repo-depth-guard.sh
if ! repo_depth_ok; then repo_depth_banner "内审 DIGEST 抽取器"; exit 3; fi

D="${1:-$(date +%F)}"
SRC="docs/internal-audit/${D}-auditor.md"
OUT="gm-inbox/AUDIT-${D}-DIGEST.md"

[ -f "$SRC" ] || { echo "🔴 正本不在：\`$SRC\` —— 本器不出件。"; exit 2; }

HAS_G=$(grep -c '^### §庚' "$SRC" || true)
HAS_J=$(grep -c '^### §己' "$SRC" || true)
if [ "${HAS_G:-0}" -eq 0 ] || [ "${HAS_J:-0}" -eq 0 ]; then
  echo "🔴 抽取判据未满足：§庚 命中 ${HAS_G}／§己 命中 ${HAS_J} —— **两节缺任一即不出件**。"
  echo "   **宁可不出，不可出一份看起来完整的半件。**"
  exit 4
fi

SHA=$(sha1sum "$SRC" | cut -d' ' -f1)
BYTES=$(wc -c < "$SRC" | tr -d ' ')
TIP=$(git log -1 --format=%H)

{
echo "# 内审官报告 · DIGEST 抽取件 · ${D}"
echo
echo "> # 🔴 **本件系抽取件，非正本。**"
echo "> **正本**：\`${SRC}\`｜**字节** ${BYTES}｜**内容 sha1** \`${SHA}\`｜**抽取 commit tip** \`${TIP}\`"
echo "> **两档比对之另一份**：\`gm-inbox/AUDIT-${D}.md\`（**全文逐字副本**·与正本 sha1 须相等）"
echo ">"
echo "> **立件依据**：\`ADJ-0801-12⑤\` —— GM 接受「只直报 §庚＋§己」之建议，"
echo "> **惟指出其物理上不可执行：GM 侧无范围读，只能整档取回。故本件把「只读一部分」变成一份真的只含那一部分的文件。**"
echo ">"
echo "> **🔴 抽取判据（预先写死·非逐案自选）**：只取 **§庚（强制回应清单）** 与 **§己（本席另行捕获）** 两整节，**逐字**。"
echo "> **本件所含内容系 \`sed\` 逐字截取，CGM 未改一字、未概括一句、未补写一行。**"
echo ">"
echo "> **🔴 本件未含之节（显式列出·免「未含」被读作「无此节」）**："
grep -E '^### §' "$SRC" | grep -vE '§庚|§己' | sed 's/^### /> - /'
echo "> - 以及正本之卷首申报块（席位／档位核／两个 as-of／库在复核期间之前进）"
echo ">"
echo "> **🔴 凡须判「内审官何以如此判」者，一律回正本读** —— 本件只含结论与其机械凭据，不含其推导。"
echo
echo "---"
echo
sed -n '/^### §庚/,/^### §辛/p' "$SRC" | sed '/^### §辛/d'
echo
echo "---"
echo
sed -n '/^### §己/,/^### §庚/p' "$SRC" | sed '/^### §庚/d'
} > "$OUT"

echo "→ 已生成 ${OUT} （$(wc -c < "$OUT" | tr -d ' ') B）"
echo "   正本 ${BYTES} B → 抽取件 $(wc -c < "$OUT" | tr -d ' ') B（**压缩比 $(echo "scale=1; $(wc -c < "$OUT")*100/${BYTES}" | bc)%**）"
