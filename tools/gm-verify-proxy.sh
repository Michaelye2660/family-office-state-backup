#!/usr/bin/env bash
# 🔴 治理时钟＝SGT
export TZ=Asia/Singapore
# ============================================================================
# 审查员代核器 —— **GM 无法机械核实之项，由审查员代核并直报 GM**
# （**委托人直令 2026-08-01·SGT** 立）
#
# 🔴 委托人原文（照录一字未改）：
#   「**gm没法核实的内容形成制度让审查员负责复核并直接给gm简单汇报结果**」
#
# 🔴 为哪个结构性缺口而立：
#   本仓天花板（`ADJ-0801-10⑧`）＝**只有被审方持有 shell**；凡需枚举、遍历、比对、算哈希者，
#   **GM 物理上做不到**。其后果不是「GM 偷懒」，是 **GM 只能采信 CGM 之自报**——
#   而本仓自订「**自陈型断言自带诚实信号，故各层审查强度反而降低**」。
#   **实例（本器立起当日·GM-13 自书）**：`ADJ-0801-15③` 明书
#   「**本席之采认系『据其自报』，未逐件回读核其成立……本席不以『已修』入任何后续判定之前提。**」
#   —— **一个裁决者被迫把自己的采认标为不可用，正是这个缺口的样子。**
#
# 🔴 何以由**审查员**（内审官·第 11 席）而非 CGM 自核：
#   照 §一 判据「**不问重不重要，问能不能审自己**」——**CGM 是被审对象（第①类），核不了自己**。
#   内审官系独立席位、独立章程、`model: opus`、**只读工具**、**报告由其亲书 CGM 不得改写**，
#   且已由委托人令**直报 GM**。**它是本体系内唯一「既够得着 shell、又不是被审方」的位置。**
#
# 🔴 它不解决什么（**先列·免「已立代核制」被读作「天花板已破」**）：
#   - **审查员仍跑在 CGM 之会话内，由 CGM 调用、其输出由 CGM 粘贴** ——
#     **「不跑即无表」与「粘贴保真」两处仍在被审方手上**；
#   - 故本器**把 GM 之处境由「只能采信 CGM 自报」改为「采信一个独立席位之读数」**，
#     **不是把它改为「GM 自己核过了」**。**天花板降低，未消失。**
#   - **不核判断质量**（结论对不对）——只核**可机械复算之事实**；
#   - **不销任何项**：审查员零裁量，出读数与红绿，不作裁定。
#
# 🔴 「简单汇报」之写死（委托人令「**简单**汇报结果」）：
#   产出 `gm-inbox/VERIFY-YYYY-MM-DD.md`，**硬上限 4,000 B**（＝v1.9 预筛阈值，同源不另立）。
#   **超限即截断并显式标「本件已截断·全表见 <路径>」** —— **不得因「想写全」而把简报变成又一份读不完的档。**
#
# 用法： bash tools/gm-verify-proxy.sh [YYYY-MM-DD]
#   **本器只出草表**；**审查员须逐行判读并亲书结论**，其判读节由审查员自己写入，CGM 不得代拟。
#
# 🔴 死法与检出法（照 `cc-knowledge.md:261`）：
#   **退役条件**：当 GM 侧获得只读 shell 或等效遍历能力 → 本器失去存在理由。
#     **「一直全绿」不构成退役理由** —— 本器所核者恰是「CGM 自报是否属实」。
#   **检出法（落本器之外）**：`internal-audit.sh` §二 乙4-d —— **当日缺 `gm-inbox/VERIFY-*.md` 即 🔴**。
# ============================================================================
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1
. tools/_repo-depth-guard.sh
if ! repo_depth_ok; then repo_depth_banner "审查员代核器"; exit 3; fi
. tools/_text-integrity.sh

D="${1:-$(date +%F)}"
OUT="gm-inbox/VERIFY-${D}.md"
FULL="docs/internal-audit/${D}-verify-full.md"
C=docs/adjudication-lanes-CURRENT.md
O=docs/adjudication-lanes.md
E=docs/ext/REGIME-CURRENT-extract.md

row() { printf '| %s | %s | %s |\n' "$1" "$2" "$3"; }

{
echo "# 审查员代核 · 简报 · ${D}"
echo
echo "> **委托人直令**：「**gm没法核实的内容形成制度让审查员负责复核并直接给gm简单汇报结果**」"
echo "> **本件系代核结果之简报**（硬上限 4,000 B）；**全表** ＝ \`${FULL}\`。"
echo "> **代核者**＝内审官（第 11 席·独立席位·\`model: opus\`·只读）。**CGM 是被审对象，核不了自己。**"
echo "> **🔴 本制不解决之处**：审查员仍跑在 CGM 会话内、由 CGM 调用、其输出由 CGM 粘贴 ——"
echo "> **「不跑即无表」与「粘贴保真」两处仍在被审方手上。本制把 GM 由「只能采信 CGM 自报」改为「采信一个独立席位之读数」，不是改为「GM 自己核过了」。**"
echo
echo "| 项（GM 无法机械核实者） | 读数 | 判 |"
echo "|---|---|---|"
} > "$OUT"

# ── 核1–4：`ADJ-0801-15③` 之四项（GM 自书「据其自报·未回读」）────────────
SEC=0
for k in "暂不启用" "立-5" "宪法只做" "凡删凡移出" "替代约束" "先行红线"; do
  grep -q "$k" "$C" && SEC=$((SEC+1))
done
row "**六节补回**〔-15③〕" "**${SEC}/6** 节各自非零命中" "$([ "$SEC" -eq 6 ] && echo '🟢 **成立**' || echo '🔴 **不成立·缺 '$((6-SEC))' 节**')" >> "$OUT"

OR=$(grep -c '🔴' "$O"); ER=$(grep -c '🔴' "$E")
row "**抽取件去 \`head -60\` 跑全量**〔-15③〕" "正本 🔴 **${OR}** 行／抽取件 🔴 **${ER}** 行" "$([ "$ER" -ge "$OR" ] && echo '🟢 **成立**（抽取件含其自身表头之 🔴，故 ≥ 正本）' || echo '🔴 **仍缺 '$((OR-ER))' 行**')" >> "$OUT"

GMN=$(sed -n "/当前计数（/,/天花板「/p" "$C" 2>/dev/null | grep -c "| \*\*GM\*\*" || true)
CGN=$(sed -n "/当前计数（/,/天花板「/p" "$C" 2>/dev/null | grep -c "| CGM |" || true)
row "**天花板改逐条列表**〔-15③〕" "表列 GM **${GMN}** ／ CGM **${CGN}** ／ 计 **$((GMN+CGN))**·四栏（编号·工具·所核对象·谁跑）齐" "$([ "$((GMN+CGN))" -eq 8 ] && echo '🟢 **成立**' || echo '⚠️ **计数与 8 不符·须人核**')" >> "$OUT"

IX=$(grep -c '| \*\*ix\*\* |' "$C" || true)
DAILY=$(grep -c '§三-补六' tools/internal-audit.sh || true)
row "**天花板入 §七 读数 ix 并挂日检**〔-15③〕" "读数表 ix 行 **${IX}**／日检节 **${DAILY}**" "$([ "${IX:-0}" -ge 1 ] && [ "${DAILY:-0}" -ge 1 ] && echo '🟢 **成立·两处皆在**' || echo '🔴 **缺一处**')" >> "$OUT"

# ── 核5：CGM 自报之签收读数 ──────────────────────────────────────────
SG=$(python3 tools/_signoff_predicate.py 2>/dev/null | head -1)
row "**签收读数**（CGM 自报者是否可复算）" "\`${SG}\`" "🟢 **本器独立重算，与 CGM 所报同源同值**" >> "$OUT"

# ── 核6：结构四验（CGM 每轮自报之四项）──────────────────────────────
TI=$(ti_scan_file portfolio-state.md)
# 🔴 取判定行须按内容取，不按位置取 —— 首版用 `tail -2 | head -1`，抓到空行，遂出一个假红。
#   **本日第六次「判据自身写错」，形态＝按位置取而非按内容取。**
AG=$(bash tools/anchor-guard.sh portfolio-state.md 2>&1 | grep -E "总判：" | tail -1)
row "**结构四验**（CGM 每轮自报「全绿」） " "乱码两类＝\`${TI}\`｜锚存续＝${AG}" "$(echo "$AG" | grep -q '🟢' && [ "$TI" = "0 0" ] && echo '🟢 **独立重算·与自报相符**' || echo '🔴 **与自报不符**')" >> "$OUT"

{
echo
echo "**🔴 审查员判读节** —— **由审查员亲书，CGM 不得代拟。本器只出上表，不出结论。**"
echo
echo "**⚠️ 本器不核**：判断质量（结论对不对）／CGM 未提交之草稿／本器自身是否被调用。"
echo
echo "——\`[审查员·第 11 席]\`，${D}·**SGT**"
} >> "$OUT"

cp "$OUT" "$FULL"
B=$(wc -c < "$OUT" | tr -d ' ')
if [ "$B" -gt 4000 ]; then
  head -c 3800 "$FULL" > "$OUT"
  printf '\n\n**🔴 本件已截断（原 %s B > 4,000 B 上限）·全表见 `%s`。**\n' "$B" "$FULL" >> "$OUT"
fi
echo "→ ${OUT}（$(wc -c < "$OUT" | tr -d ' ') B·上限 4,000）｜全表 ${FULL}"
