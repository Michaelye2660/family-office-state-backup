#       浅克隆下两向皆 false（共同祖先在截断线外）且 `2>/dev/null` 吞掉成因 → 落 else → 报 🔴「疑改写历史」**。
#       **🔴 惟其已于第 36–37 行挂本核且 fail-closed（`exit 3`），故实际跑不到丙5 —— 该路径已被挡住。**
