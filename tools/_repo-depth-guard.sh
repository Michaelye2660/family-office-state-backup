#   🔴 **它坏掉时的表面**：一张格式完整、计数齐全、每一栏都在、**且比昨天更好看**的绿表。
#      ——正是 CGM-G4 交接书 §五-1 所记之共性（「本席造的检查器，坏的时候输出都是看起来完整的」）
#      之又一例，**而这一次坏的不是判据本身，是判据所依赖之环境前提，且从未有人断言过它**。
