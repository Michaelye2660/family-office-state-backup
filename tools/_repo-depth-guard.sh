#
# 🔴 已知波及面（本轮机械枚举·`grep -l "git log\|--diff-filter" tools/*`）：
#   `signoff-queue.sh`（入队时点）／`activate-epoch.sh`（声明件首次加入之 commit ＝ ACT）／
#   `daily-recon.sh`（源⑦b 覆盖核之末次提交时点、其后提交计数）／
#   `signoff-verify.sh`（所引 commit「是否在史」——浅克隆下会把在史之历史 commit 报成不在史）。
#   **四器皆已挂本核。** 未挂者系不依赖历史深度（只用 HEAD 或只读文件），本行即其申报。
#
# ── 🔴 射程扩容 · 第二类：**分叉类判断**（CGM-G6 补·2026-08-02·委托人直令「3 一起办」）──
#   **原文以上一律不改**（追加式）。本节所补者非新器，是**把本器射程之第二半写出来**。
#
#   **实证（2026-08-02·CGM-G6 就位第 0 步）**：浅克隆不只让读数变绿，**它会伪装成一次真实的历史分叉**。
#   `git pull` 报出三条信号 —— **本地与 origin 各 50 commit 分叉**／**`merge-base` 返回空**／
#   **fetch 标 `forced update`**（且其所印旧值恰为本地 HEAD，读起来正像「远端把你脚下这笔重写了」，
#   即撞上本仓红线第 1 条「永不 force-push、永不重写 master 历史」）。
#   **三条看起来互相印证，而三条同源于 `--depth 50`。** `--unshallow` 后复算：
#   `merge-base` ＝ 本地 HEAD，本地系 origin/master **直系祖先**，仅落后 85 个 commit，`--ff-only` 即毕。
#
#   **🔴 与第一类之别，须分开记**：
#     **读数类之坏 ＝ 假绿**（该红不红，如逾时限 48 静默变 0）；
#     **分叉类之坏 ＝ 假红，且是最重的那种红** —— 它不指向「某个数不准」，它指向「有人重写了历史」。
#     **更要命者：照它处置，两条路都是实质性破坏** —— 判「远端重写」则强推或重置，**丢掉那 85 个 commit**；
#     判「两边都要保」则 merge，**造出一套重复历史**。**没有一条是「稍微不准」。**
#
#   **一句通则（本器所治者之一般形态）**：
#     **互相印证的多条信号，若共用同一个前提，其印证力等于一条。**
#     本仓既有之说法是「先证地面是真的，再信尺上的数」；**本条为其补一格：**
#     **地面不真时，尺子不是读错一个数，是整张图都自洽地错。**
