# ============================================================================
# 仓库历史深度前置核 —— **单一判据正本**（CGM-G5 立 · 2026-08-01 · SGT）
#
# 🔴 为哪次事故而立（照本仓通则：每个器之文件头写明它自己是为哪次事故而生）：
#   CGM-G5 就位当轮完成重建阅读后首跑 `tools/signoff-queue.sh`，得
#   **「龄分布：≤3 日 84 件」／「逾时限（代理判）＝0 件」／🟢 无逾时限件**；
#   而前任 CGM-G4 于**同一日、同一 HEAD**（`fd1d058`）之实测为
#   **36／30／18 · 逾时限 48**（〔M〕476④ 与 `docs/daily-recon/2026-08-01.md` 在库可对）。
#
#   查因＝**换代所开之新容器，其仓库克隆系浅克隆**：
#     `git rev-parse --is-shallow-repository` ＝ **true**；全库仅 **50** 个提交；
#     最早提交 `abd10e3`（2026-07-31T14:05Z）＝**浅边界**。
#   于是 `git log --diff-filter=A -- <file>` 对**一切早于浅边界之文件**一律返回该边界提交
#   → 全部回执之「入队时点」被压成同一日 → 龄全部 ≤3 日 → **逾时限 48 静默变 0**。
#   `git fetch --unshallow` 后**同器、同 commit、同参数**复跑，读数即回到 36／30／18・逾时限 48。
#
#   🔴 **它坏掉时的表面**：一张格式完整、计数齐全、每一栏都在、**且比昨天更好看**的绿表。
#      ——正是 CGM-G4 交接书 §五-1 所记之共性（「本席造的检查器，坏的时候输出都是看起来完整的」）
#      之又一例，**而这一次坏的不是判据本身，是判据所依赖之环境前提，且从未有人断言过它**。
#
#   同族前科一次：〔M〕467④（relay 仓 `--depth 1` 致「一次加入 90 余文件」之假象）。
#   **差别在于**：那次落在只读之中转仓、当场识破；**这次落在主仓之治理闸上，且默认方向是绿的**，
#   并且**每一次 CGM／GM 换代都会重新开一个新容器**——故它不是偶发，是**换代之常态前提**。
#
# 🔴 它不核什么（先列不覆盖处·免「未报」被读作「已核无事」）：
#   - 只核「本地历史是否完整」，**不核历史内容是否正确**、不核是否与 origin 一致；
#   - 不核工作树是否干净、不核 remote 是否领先；
#   - **不自动修复**——**不代跑 `git fetch --unshallow`**：那是改动仓库状态，
#     须由人或调用方显式决定；一个会自己把前提改掉的前置核，等于没有前置核。
#
# 🔴 已知波及面（本轮机械枚举·`grep -l "git log\|--diff-filter" tools/*`）：
#   `signoff-queue.sh`（入队时点）／`activate-epoch.sh`（声明件首次加入之 commit ＝ ACT）／
#   `daily-recon.sh`（源⑦b 覆盖核之末次提交时点、其后提交计数）／
#   `signoff-verify.sh`（所引 commit「是否在史」——浅克隆下会把在史之历史 commit 报成不在史）。
#   **四器皆已挂本核。** 未挂者系不依赖历史深度（只用 HEAD 或只读文件），本行即其申报。
#
# 用法：
#   source tools/_repo-depth-guard.sh
#   repo_depth_ok            # 返回 0＝历史完整；1＝浅克隆
#   repo_depth_banner "器名"  # 印一段 🔴 markdown 块（含自救命令），供 fail-closed 时输出
#
# 🔴 死法与检出法（**内审官 R5 强制回应·2026-08-01 补**·违 `cc-knowledge.md:261`「凡新增结构立时即写其退役条件」）：
#   **退役条件**：当会话环境改为**默认全克隆**（连续 30 日 `is-shallow-repository` 恒为 false，且期间发生过至少两次换代）→ 得呈请退役。
#   **「一直没报红」不构成退役理由** —— 本器所防者恰是「默认绿」。
#   **检出法（落在本器之外）**：`daily-recon.sh` **源⓪** 每日出其读数；**源⓪ 缺行即视同本器未挂**。
# ============================================================================

repo_depth_ok() {
  local s
  s="$(git rev-parse --is-shallow-repository 2>/dev/null)"
  # 🔴 fail-closed：取不到读数（旧 git／非仓库）一律当作「不可信」，不当作「完整」
  [ "$s" = "false" ]
}

repo_depth_banner() {
  local who="${1:-本器}"
  local n
  n="$(git rev-list --count HEAD 2>/dev/null || echo '?')"
  printf '%s\n' \
"# 🔴 ${who} 前置核未过：**本仓系浅克隆，历史深度不足**" \
"" \
"| 项 | 读数 |" \
"|---|---|" \
"| \`git rev-parse --is-shallow-repository\` | \`$(git rev-parse --is-shallow-repository 2>/dev/null || echo 'ERR')\` |" \
"| 本地提交总数 | ${n} |" \
"| 浅边界（最早可见提交） | \`$(git log --reverse --format='%h %aI' 2>/dev/null | head -1 || echo 'ERR')\` |" \
"" \
"**故本器不出任何龄／时点／在史类读数** —— 在浅克隆下这些读数**会静默偏向「更好看」的一侧**" \
"（一切早于浅边界之文件，其首次加入提交被解析为边界提交本身）。" \
"" \
"**🔴 不出错误读数，优于出一个看起来完整的绿表。**" \
"" \
"**自救（须由人或调用方显式决定，本器不代跑）**：" \
"" \
'```' \
"git fetch --unshallow origin      # 或： git fetch --deepen=<N>" \
'```' \
"" \
"复原后同 commit 复跑本器即可；**若读数与复跑前不同，以复跑后为准，并须于回执如实书两个读数**。" \
""
}
