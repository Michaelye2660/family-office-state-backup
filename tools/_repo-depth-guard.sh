#   **🔴 射程内而本器管不到的一处（先列·免被读作已覆盖）**：
#     **人在命令行上手敲之分叉判断，不受任何器保护。** 2026-08-02 那次即此 ——
#     **本器只能被脚本 `source`，拦不住一个人读着 `git pull` 的输出下结论。**
#     **故留一条可复跑之自检，供任何人在见到「diverged／merge-base 为空／forced update」时先跑**：
#       `git rev-parse --is-shallow-repository`   # true ＝ 先 `git fetch --unshallow`，再谈分叉
#     **该自检不在本器内，因为需要它的时刻本器尚未被调用** —— **一个只在脚本里生效的前置核，
#     挡不住脚本之外的判断。此系本器之结构性限度，不因本次扩容而消除。**
#
# 用法：
#   source tools/_repo-depth-guard.sh
#   repo_depth_ok            # 返回 0＝历史完整；1＝浅克隆
#   repo_depth_banner "器名"  # 印一段 🔴 markdown 块（含自救命令），供 fail-closed 时输出
#
# 🔴 死法与检出法（**内审官 R5 强制回应·2026-08-01 补**·违 `cc-knowledge.md:261`「凡新增结构立时即写其退役条件」）：
#   **退役条件**：当会话环境改为**默认全克隆**（连续 30 日 `is-shallow-repository` 恒为 false，且期间发生过至少两次换代）→ 得呈请退役。
#   **「一直没报红」不构成退役理由** —— 本器所防者恰是「默认绿」。
#   **检出法（落在本器之外）**：`daily-recon.sh` **源⓪** 每日出其读数；**源⓪ 缺行即视同本器未挂**。
