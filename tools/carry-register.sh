# 纪元结转登记器 —— **历史待签回执之批量机械处理**（`ADJ-0801-15⑥` 三分法之落地）
#
# 🔴 它做什么 / 🔴 它**绝不**做什么（**本器最要紧之一条，先写**）：
#   做：**维一·机械核**（四字段在否／件头格式／收件七步之承重两步 ③④ 留痕）
#     ＋ **纪元结转登记**＝`ADJ-0801-05①` 之**乙义：知悉而不追认**。
#   **绝不做**：**签收**。**本器不写、不生成、不暗示任何「已签」「已核」「维二」之字样。**
#
#   **判据照录（CGM 自书·GM-13 于 `-15⑥` 原样援用为硬约束）**：
#     **「批量签一份未读之回执，是把『未核』变成『已核』之留痕，比不签更坏。」**
#   **故本器之每一行强制带「未经维二」四字**，且**结转登记与签收在读数上分栏**，
#   **混栏即本制不成立**（`-15⑥` 硬约束 1）。
#
# 🔴 何以「结转登记」不是「签收」（**须能一句说清，否则这一制迟早被读成签收**）：
#   **签收＝已阅并认可**（维一＋维二）；**结转登记＝知悉其存在并承接，未对其内容表态**。
#   前者是判断，**只有 GM 能作**（G1）；后者是记账，**CGM 可批量办**。
#   **一份结转登记不减少 GM 之工作，它只是把「还没人看过」这件事记成可数的。**
#
# 🔴 它不核什么（先列不覆盖处）：
#   - **不核「裁得对不对」**——属维二，归 GM 抽样；
#   - **不核回执内容是否属实**——只核**形式要件在否**；
#   - **不核该件是否本就该签**——存量之应签与否属判断类；
#   - **不核本器是否被跑**——自指盲区，归内审官。
#
# 🔴 死法与检出法（照 `cc-knowledge.md:261`）：
#   **退役条件**：当结转登记存量归零且新制（五段签收标记）现役满 60 日 → 本器得呈请退役。
#     **「一直跑得很顺」不构成退役理由。**
#   **检出法（落本器之外）**：`internal-audit.sh` §二 **乙4-e** —— **逐行判，非整档判**：
#     **任一数据行（`| N |` 起首）含「已签／已核／维二通过」而该行无「未经维二」→ 🔴**；
#     **另核数据行总数 ＝ 带「未经维二」之行数**，二者不等即 🔴（**挡「整行漏标」**）。
#   🔴 **本条原作「凡结转登记表内出现…而无…者即 🔴」——审查员指其可被读作整档 AND，
#     而本表 91 处「未经维二」会令整档式永不触发（写死永不会红）。已改为逐行式，并已落器实测双向。**
#   🔴 **并记一处 as-of**：审查员代核时报「内审器无 乙4-e」——**属实，其启动早于本席落该检出**；
#     **本席不以「后来加了」抹去那一刻它是对的这件事**。
#
# 用法： bash tools/carry-register.sh [输出路径]
# ============================================================================
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1
. tools/_repo-depth-guard.sh
if ! repo_depth_ok; then repo_depth_banner "纪元结转登记器"; exit 3; fi

OUT="${1:-docs/internal-audit/$(date +%F)-carry-register.md}"
mkdir -p "$(dirname "$OUT")"

python3 - "$OUT" <<'PYEOF'
import sys, io, os, glob, re, subprocess
sys.path.insert(0, 'tools')
from _signoff_predicate import is_signed, is_carried

out = sys.argv[1]
files = [f for f in sorted(glob.glob('adj-archive/*receipt*.md')) if 'signoff' not in f]
uns = [f for f in files if not is_signed(f)]

rows, stat = [], {'四字段': 0, '四字段-仅字样': 0, '件头': 0, '承重③': 0, '承重④': 0, '已结转': 0}
for f in uns:
    t = io.open(f, encoding='utf-8', errors='replace').read()
    base = os.path.basename(f).replace('-receipt.md', '')
    # 🔴 审查员 2026-08-01 落库前代核之红 1：本器初版之「四字段」与「承重③」**系同一条正则**
    #   （`GM_EPOCH|四字段` vs `四字段|GM_EPOCH`）→ 两栏逐行必然同值。
    #   **其判词照录**：**「两个 91/91 不是两项证据，是一项数了两遍。」**
    # 🔴 红 2：满分之来源 —— 91 件中真含 `GM_EPOCH` 者仅 **65**，**26 件仅凭散文里「四字段」四个字过关**。
    #   **此系 `_signoff_predicate.py` 自书「散文里的两个字不能当判据」之同形复发，换了个器再犯一次。**
    # **改法**：两栏各自独立且各有分辨力 ——
    #   `c4` ＝ **严格**：须真含 `GM_EPOCH` 字面（四字段之实体）；
    #   `s3` ＝ **承重步③之留痕**：须有「四字段核／逐字核」之动作词，**而非只提及该词**。
    c4 = '✅' if 'GM_EPOCH' in t else ('〰' if '四字段' in t else '—')
    hd = '✅' if t.lstrip().startswith('#') else '—'
    s3 = '✅' if re.search(r'四字段(逐字)?核|四字段.{0,6}核|逐字校验', t) else '—'
    s4 = '✅' if (re.search(r'三要素|三要件', t) and re.search(r'轮号|轮:|轮 ', t)) else '—'
    cr = '✅' if is_carried(f, t) else '—'
    for k, v in (('四字段', c4), ('件头', hd), ('承重③', s3), ('承重④', s4), ('已结转', cr)):
        if v == '✅': stat[k] += 1
    if c4 == '〰': stat['四字段-仅字样'] += 1
    rows.append((base, c4, hd, s3, s4, cr))

tip = subprocess.run(['git', 'log', '-1', '--format=%H'], capture_output=True, text=True).stdout.strip()

L = []
A = L.append
A('# 纪元结转登记 · 逐份表（**`ADJ-0801-15⑥` 三分法之维一 ＋ 历史存量**）')
A('')
A('> # 🔴 **本表不是签收。一行也不是。**')
A('> **结转登记 ＝ `ADJ-0801-05①` 之乙义：知悉而不追认。** **签收 ＝ 已阅并认可（维一＋维二），只有 GM 能作（G1）。**')
A('> **本表之每一行皆标「未经维二」** —— **判据照录（CGM 自书·GM-13 于 `-15⑥` 原样援用）**：')
A('> **「批量签一份未读之回执，是把『未核』变成『已核』之留痕，比不签更坏。」**')
A('>')
A('> **🔴 本表不减少 GM 之工作。** 它只是把「还没人看过」这件事**记成可数的**。')
A('> **维二（裁得对不对）一件未办**，照 `-15⑥` 归 GM 抽样，**并入周二次批次·每批 ≥5 件·逐批书抽样率与方法**。')
A('>')
A(f'> **生成**：`bash tools/carry-register.sh`｜**读取 commit**：`{tip}`｜**待签存量**：**{len(uns)}** 件（全库回执 {len(files)} 件）')
A('')
A('## 一 · 维一机械核 · 汇总')
A('')
A('| 项 | 命中 / 存量 | 说明 |')
A('|---|---|---|')
A(f'| 四字段（**严格·真含 `GM_EPOCH`**） | **{stat["四字段"]} / {len(uns)}** | 只核**在否**，不核值对不对 |')
A(f'| 🔴 四字段（**仅凭散文「四字段」字样过关**·`〰`） | **{stat["四字段-仅字样"]} / {len(uns)}** | **审查员代核所捕**：初版以 `GM_EPOCH\|四字段` 判，**这 {stat["四字段-仅字样"]} 件并无四字段实体**，只是文中提过那四个字。**「散文里的两个字不能当判据」之同形复发。** |')
A(f'| 件头格式 | **{stat["件头"]} / {len(uns)}** | 🟡 **审查员标其无分辨力**：`startswith("#")` 对 md 近乎恒真，**全库 0 件失败**。**留之，但不得作为「已核」之凭据。** |')
A(f'| 承重步③（**四字段核之动作留痕**） | **{stat["承重③"]} / {len(uns)}** | **已与「四字段」栏解耦**——初版二者系同一条正则，**「两个 91/91 不是两项证据，是一项数了两遍」**（审查员语） |')
A(f'| 承重步④（三要素＋轮号） | **{stat["承重④"]} / {len(uns)}** | 同上 |')
A(f'| 已有结转登记字样 | **{stat["已结转"]} / {len(uns)}** | 本轮之前即有者 |')
A('')
A('**⚠️ 承重两步之低命中率不构成「这些回执有问题」** —— **它们全部写于 `-12①` 立规之前**，')
A('**照 v1.9 §六 之同一条：一条新规不得追溯地把旧件染红。** 本表出数，**不判红**。')
A('')
A('## 二 · 逐份表（**每行末栏即其结转登记·一律「未经维二」**）')
A('')
A('| # | 件 | 四字段 | 件头 | ③ | ④ | 原有结转 | **结转登记** |')
A('|---:|---|:-:|:-:|:-:|:-:|:-:|---|')
for i, (b, c4, hd, s3, s4, cr) in enumerate(rows, 1):
    A(f'| {i} | `{b}` | {c4} | {hd} | {s3} | {s4} | {cr} | **知悉而不追认·未经维二** |')
A('')
A('---')
A('')
A('## 三 · 🔴 本表**未**做之事（**先列·免被读作已办**）')
A('')
A('1. **一件也没签收。** 91 个数据行之末栏一律「知悉而不追认·未经维二」，**零行例外**（可机械复算）。')
A('   **🔴 本行原作「本表零处出现〔那两个词〕」——审查员指其自我否证（该句自己就含那两个词），且会污染任何 grep 检出。已改为按数据行陈述。**')
A('2. **未核任何回执之内容是否属实** —— 只核形式要件在否。')
A('3. **未核该件是否本就该签** —— 存量之应签与否属判断类。')
A('4. **未减少 GM 之工作** —— 维二 **{}** 件仍在 GM 处，一件未动。'.format(len(uns)))
A('')
A('## 四 · 🔴 本轮新增件号（**审查员代核所令·免下轮又对不上**）')
A('')
A('**上一次代核时之存量读数＝90**，本表＝**{}**。**差异之来源须固定记，不得每轮重新推**：'.format(len(uns)))
A('')
NEW = [b for b, *_ in rows if b.startswith('ADJ-0801-')]
A('- **本日（08-01）新增而入队之件**：`' + '` / `'.join(NEW) + '`（**{} 件**）'.format(len(NEW)))
A('- **🔴 其中含 `ADJ-0801-15`** —— **即写下「先出逐份表候审查员代核再落库」那句承诺的那份回执自己，也在待签队里。**')
A('- **⚠️ 90 之读数全库无留痕**（系上一次代核之口径），**本席无法机械复算它**；')
A('  **故本表只固定「本轮之数与其构成」，不主张 90→91 之差已被完全解释。**')
A('')
A('**〔重跑／重设〕标注（v2.1）**：本表之五项维一判据 —— ')
