#!/usr/bin/env bash
# 🔴 治理时钟＝SGT
export TZ=Asia/Singapore
# ============================================================================
# 呈裁摘要件生成器（**规则三·摘要须机械抽取·禁 CGM 转写**·v1.3 §三）
#
# 🔴 为哪次事故而立：规则三之由逐字＝「**转写者会系统性弄丢对自己不利的条款**」
#   （失败模式册第⑧项·转写稀释→双向方向学·ADJ-0714-04⑬）；
#   **CGM 既是被审方，其手写摘要即让被审方决定裁决方看得见什么。**
#   故本器**逐字截取标题行与带 🔴 之条款行，不改、不概括、不补写**。
#
# 🔴 它不核什么：**不判摘要够不够**（属判断类·归 GM 签收之维二）；
#   **不判所选之节对不对**——**故必须同时输出「本摘要未含之节」全表**，
#   使「未含」与「无此节」不可混。
#
# 🔴 死法与检出法（**内审官 R5 强制回应·2026-08-01 补**·违 `cc-knowledge.md:261`「凡新增结构立时即写其退役条件」）：
#   **退役条件**：当 GM 侧获得范围读或仓库 shell（即其可自行抽取）→ 本器失去存在理由，得呈请退役。
#   **检出法（落在本器之外）**：`internal-audit.sh` **自检2 · 全库 UTF-8 合法性** ——
#   **本器系本日唯一一个首跑即把坏件推进 master 者**，其失效形态即「产出非法 UTF-8 而不报错」。
#   **另**：凡本器之产出被引用于任何申报（封存清单／呈裁件），**该申报须随产出重生成而同轮更新** ——
#   **改了物没改指向那个物的申报，本日已实证两次**（内审官 R2）。
# ============================================================================
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1
. tools/_repo-depth-guard.sh
if ! repo_depth_ok; then repo_depth_banner "呈裁摘要生成器"; exit 3; fi
OUT="${1:?用法: gen-submission-summary.sh <输出路径> <源文件…>}"; shift
COMMIT=$(git log -1 --format=%H)
{
echo "# 呈裁摘要件（**机械抽取·逐字·非转写**·规则三／v1.3 §三 摘要前置）"
echo
echo "> **生成**：\`bash tools/gen-submission-summary.sh\`｜**抽取 commit tip**：\`$COMMIT\`｜**生成时点**：$(git log -1 --format=%ad --date=format-local:'%Y-%m-%d %H:%M') SGT"
echo "> **🔴 抽取判据（预先写死·非逐案自选）**：① 各源之**全部标题行**（\`#\`/\`##\`/\`###\`）逐字；② 各源内**含 🔴 之行**逐字（该仓以 🔴 标其自认最要紧者）；**③ 除此之外一字未取**。"
echo "> **🔴 本器不判摘要够不够**（属判断类·归 GM 签收之维二）；**故同时输出「本摘要未含之节」全表**，使「未含」与「无此节」不可混。"
echo "> **禁转写**：本件所有内容系 \`sed\`/\`grep\` 逐字截取，**CGM 未改一字、未概括一句、未补写一行**。"
echo
for f in "$@"; do
  [ -f "$f" ] || { echo "## 🔴 源缺失：\`$f\`"; continue; }
  B=$(wc -c < "$f" | tr -d ' '); S=$(sha1sum "$f" | cut -d' ' -f1)
  echo "---"; echo
  echo "## 源 · \`$f\`"; echo
  echo "- **正本路径**：\`$f\`｜**字节**：$B｜**内容 sha1**：\`$S\`"
  echo
  echo "### 全部标题行（逐字）"; echo
  echo '```'
  grep -nE '^#{1,4} ' "$f" || echo "（无标题行）"
  echo '```'
  echo
  echo "### 含 🔴 之行（逐字·截前 200 字）"; echo
  echo '```'
  # 🔴 按字符截，非按字节（CGM-G5 修·2026-08-01）：初版用 `cut -c1-200`，
  #   在多字节中文上**从半个字符中间切开，产出非法 UTF-8** —— G4 已记之同族坑
  #   （`cut -c` 按字节切／`grep -oE {0,40}` 同病），**而本器首跑即复犯，且已随 commit 2443573 入 master**。
  #   **共性一句：坏掉的是载体不是内容——内容本身正确，毁于传输层。**
  grep -n '🔴' "$f" | head -60 | python3 -c "
import sys
for l in sys.stdin:
    l=l.rstrip('\n')
    print(l if len(l)<=200 else l[:200]+'…')
" || echo "（无）"
  echo '```'
  N=$(grep -c '🔴' "$f" || true); M=$(grep -c '🔴' "$f" || true)
  if [ "${N:-0}" -gt 60 ]; then echo; echo "**⚠️ 本源含 🔴 之行共 ${N} 条，上表只列前 60 条 —— 余 $((N-60)) 条未列，须读正本。**"; fi
  echo
  echo "### 🔴 本摘要**未含**之内容（如实列·免「未报」被读作「无此节」）"; echo
  echo "- **正文散文全部未含** —— 本器只取标题行与 🔴 行；**一切论证、理由、表格内容、沿革注、代码，一字未取**。"
  echo "- **须读正本之情形**：凡欲判断「该裁得对不对」者 —— **摘要只能告诉你有哪些条，告诉不了你那些条是否成立**。"
  echo
done
echo "---"; echo
echo "**🔴 摘要前置硬顺序之申报（v1.3 §三）**：本件系**摘要件**，须**先落库**；呈裁件**后落**，两个独立 commit，**顺序不可颠倒**。**违反之效果＝该呈裁件不成立，GM 得直接退回不须理由。**"
echo
echo "*生成于 \`tools/gen-submission-summary.sh\`｜逐字抽取·禁转写｜**CGM 未改一字***"
} > "$OUT"
echo "→ 已生成 $OUT （$(wc -c < "$OUT" | tr -d ' ') B）"
