  #   **故此后一切说明一律写在 shell 注释里，不进双引号。**
  grep -n '🔴' "$f" | python3 -c '
import sys
for l in sys.stdin:
    print(l.rstrip("\n"))
' || echo "（无）"
  echo '```'
  N=$(grep -c '🔴' "$f" || true); M=$(grep -c '🔴' "$f" || true)
  # 🔴 本行原印「上表只列前 60 条 —— 余 N 条未列」，**而行截与字截皆已去除**（`-15④`／审查员行 2）。
  #   **一句陈述截断的框架文字，在截断已不存在之后仍在印** —— **它自己成了那份不实申报**。
