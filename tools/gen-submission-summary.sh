for f in "$@"; do
  [ -f "$f" ] || { echo "## 🔴 源缺失：\`$f\`"; continue; }
  B=$(wc -c < "$f" | tr -d ' '); S=$(sha1sum "$f" | cut -d' ' -f1)
  echo "---"; echo
  echo "## 源 · \`$f\`"; echo
  echo "- **正本路径**：\`$f\`｜**字节**：$B｜**内容 sha1**：\`$S\`"
  echo
  echo "### 全部标题行（逐字）"; echo
  echo '```'
  grep -nE '^#{1,4} ' "$f" || echo "（无标题行）"
  echo '```'
  echo
  echo "### 含 🔴 之行（**逐字·全量·无行截无字截**）"; echo
  echo '```'
  # 🔴 按字符截，非按字节（CGM-G5 修·2026-08-01）：初版用 `cut -c1-200`，
  #   在多字节中文上**从半个字符中间切开，产出非法 UTF-8** —— G4 已记之同族坑
  #   （`cut -c` 按字节切／`grep -oE {0,40}` 同病），**而本器首跑即复犯，且已随 commit 2443573 入 master**。
  #   **共性一句：坏掉的是载体不是内容——内容本身正确，毁于传输层。**
  # 🔴 `ADJ-0801-15④`（GM-13 捕·2026-08-01）：原作 `head -60`，**致抽取件只覆盖前 60 条 🔴**。
  #   **一把缺四成的尺，不能当控制器用** —— 而本器之全部存在理由，正是「CGM 之转写会系统性弄丢
  #   对自己不利的条款，故须有一份非转写者供对照」。**一个被截断的对照件，其漏掉的那四成正好无人复核。**
  #   **改为全量，不设上限。** 若某日产出过大，**须另立分卷而非截断**——截断使「未含」与「不存在」不可分。
  # 🔴 审查员 2026-08-01 代核之唯一 🔴：本块原作 `l[:200]+'…'`，**字符级截断仍现役**。
  #   `ADJ-0801-15④` 所修者只是行级截断（`head -60`）；上文自书「改为全量，不设上限……须另立分卷而非
  #   截断」，**该令只落到行轴，未落到字符轴**。
  #   **实害**：正本 v1.6 沿革行（858 B）被砍至 466 B，**砍掉的正是「改了什么」之尾**——
  #   而那段尾巴恰是本席自曝之三处失守（外审实为单席／brief 漏索环境表／独立镜像不可实现）。
  #   **截断又一次专挑对本席不利的那一段。** 本器表头自书「CGM 未改一字」——**该句曾在此被证伪。**
  #
  # 🔴 并记一处修它时当场犯的错（同族第三次·本日第 8 次「判据自身写错」）：
  #   本席初版把上列说明**写在 `python3 -c "…"` 之双引号内**，其中之反引号被 bash 当命令替换执行，
