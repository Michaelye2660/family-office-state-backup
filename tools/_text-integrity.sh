# 内部：以 python3 为准（与 `tools/signoff-verify.sh:113` 之历史判据同一实现，不另造第二把尺）
_ti_py() {
  python3 - "$@" <<'PYEOF'
import re, sys
tot_f = tot_m = 0
for p in sys.argv[1:]:
    try:
        t = open(p, encoding='utf-8', errors='ignore').read()
    except Exception:
        continue
    tot_f += t.count(chr(0xFFFD))
    tot_m += len(re.findall(r'[À-ÿ]{2,}', t))
print(tot_f, tot_m)
PYEOF
}

ti_scan_file() {
  [ -f "$1" ] || { echo "ERR ERR"; return 2; }
  _ti_py "$1"
}

ti_ok() {
  local r
  r="$(ti_scan_file "$1")" || return 1
  [ "$r" = "0 0" ]
}

# 全库扫描；$1 可给 glob（默认 tracked *.md）。印一段 markdown，供回执直接引用。
ti_scan_repo() {
  local pat="${1:-*.md}"
  local files n r fffd fancy
  # shellcheck disable=SC2207
  files=($(git ls-files -- "$pat" 2>/dev/null))
  n=${#files[@]}
  if [ "$n" -eq 0 ]; then
    echo "| 乱码两类扫描 | **范围内 0 文件** | ⚠️ **范围可能写错·不得读作「已核无事」** |"
    return 1
  fi
  r="$(_ti_py "${files[@]}")"
  fffd="${r%% *}"; fancy="${r##* }"
  printf '%s\n' \
"| 乱码两类扫描 · 范围＝tracked \`${pat}\`（**${n}** 文件） | U+FFFD ＝ **${fffd}** ／ 连续 Latin-1 花式串 ＝ **${fancy}** | $( [ "$fffd" = "0" ] && [ "$fancy" = "0" ] && echo '🟢' || echo '🔴' ) |"
  [ "$fffd" = "0" ] && [ "$fancy" = "0" ]
}

# 供自检4 用：印「手敲 shell 式」之读数，与正本式对照。**本函数刻意保留缺陷写法，是标本不是工具。**
ti_naive_shell_count() {
  # 缺陷复现：不设 locale 之 grep -P，按字节解释模式串
  grep -cP '[À-ÿ]{2,}' "$1" 2>/dev/null || echo 0
}
