# 文本完整性判据正本 —— **乱码两类扫描之单一实现**（CGM-G5 立 · 2026-08-01 · SGT）
#
# 🔴 为哪次事故而立（照本仓通则：每个器之文件头写明它自己是为哪次事故而生）：
#   2026-08-01·CGM-G5 于 GPT 复核卡回程时，**手敲 shell 跑第四验之花式串扫描**：
#       grep -cP '[À-ÿ]{2,}' <file>
#   得 **57 命中**。同一文件以正本判据（`tools/signoff-verify.sh:113` 之 python 路）跑，
#   得 **0**。对照组更露骨：`tools/_repo-depth-guard.sh`（本仓自造之纯净文件）同一 shell 式得 **47**。
#
#   查因＝**locale**。本会话 `LANG` 与 `LC_ALL` 皆空 → grep 走 C locale → PCRE 按**字节**解释模式；
#   而模式串 `[À-ÿ]` 本身系 UTF-8 编码之 `\xC3\x80-\xC3\xBF`，被 PCRE 读成
#   「字符集 ＝ {0xC3} ∪ [0x80-0xC3] ∪ {0xBF}」——**该区间恰好覆盖一切 UTF-8 续字节**，
#   于是**每一段中文都命中**。加 `LC_ALL=C.UTF-8` 后同文件同式即回 0。
#
#   **本次之实害＝零**（`adj-archive/` 内六份写有该扫描读数之回执，逐份查过皆书「命中零」，
#   即皆走 python 正本路，无一份被污染）。**故本器所治者系一个已现形而尚未致害之缺陷。**
#
# 🔴 它坏掉时的方向（**与深度守卫相反，须分开写**）：
#   深度守卫之坏是**假绿**（该红不红）；本缺陷之坏是**假红**（不该红而红，且红得极响：47、57、217）。
#   假红看似安全，其实更阴——**它把人训练成「那个数一向不准」**，
#   而第四验立规之全部意义，就是**让一次真命中不被当成噪声放过**。
#   （此即内审官 §丙-3 就丙5 假红所书之同一条理由：
#     「一把在最常见情形下必然报红的尺，会在几天内把人训练成不看它」。）
#
# 🔴 它不核什么（先列不覆盖处·免「未报」被读作「已核无事」）：
#   - 只核**两类既定形态**（U+FFFD ∧ 连续 Latin-1 花式串），**不核其它任何编码病**
#     （BOM、CRLF、零宽字符、同形字、全半角混用 —— **一律不在射程**）；
#   - **不核语义**：一段合法 UTF-8 的胡话，本器判绿；
#   - **不自动修复**，不改任何文件；
#   - **不核二进制文件**（调用方须自行限定扫描范围）。
#
# 🔴 何以不直接叫大家「记得加 LC_ALL」：
#   `_repo-depth-guard.sh` 之教训同型 —— **凡靠人记得的前提，早晚有一次没记得**。
#   本仓本日已实证两次同族（`cut -c` 引用过三次仍复犯／反引号转义对了 27 次漏了 2 次）。
#   **故本器之价值不在算法（算法本来就对），在于把手敲那条路彻底堵死：只留一个入口。**
#
# 用法：
#   source tools/_text-integrity.sh
#   ti_scan_file <路径>        # 印 "<fffd数> <花式串数>"；两者皆 0 即净
#   ti_scan_repo [glob]        # 全库扫描（默认 tracked 之 *.md），印汇总表 markdown
#   ti_ok <路径>               # 返回 0＝净；1＝有命中（供 if 用）
#
# 🔴 死法与检出法（**照 `cc-knowledge.md:261`·凡新增结构立时即写其退役条件**）：
#   **退役条件**：当第四验本身被废止（U+FFFD 与花式串两类不再列为落库前必扫）→ 本器随之退役。
#     **「一直没报命中」不构成退役理由** —— 本器所防者恰是「一次真命中被当噪声」。
#   **检出法（落在本器之外·不靠人记得）**：
#     `tools/internal-audit.sh` **§三-补二 自检4** 每日跑一次「手敲式 vs 正本式」之读数比对；
#     **两式读数不一致即 🔴**（说明又有人在正本之外手敲了一把尺）。**自检4 缺行即视同本器未挂。**
