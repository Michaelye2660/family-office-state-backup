   `CLAUDE.md`【取数数据链】系 -52 §一第 2 步之**明文补读项**、E10 就位声明亦列为已读，
   **而 `tools/reading-set-size.sh` 之必读集基线内并无此件**。
   → 故上表并列两个口径：**原定口径**（分子照 -53① 之列举）与**同集口径**（分子只计在分母集内者）。
   **本席不擅自把 `CLAUDE.md` 计入分母** —— 增减必读集属判断类，且 -50② 之总量闸明令
   「凡新增必读项须同时指明移出何项、或写明新总量」。**登记呈裁，不代裁。**

