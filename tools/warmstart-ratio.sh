#!/usr/bin/env bash
# 🔴 治理时钟＝SGT（ADJ-0801-01① 裁·2026-08-01·委托人「发」）
#   本体系一切「日／龄／截止日／当日摘要之当日／件号日期」之日界一律以 SGT 计。
#   依据非新造：委托人系港／新双重税务居民；早晚简报早已按 09:00／21:00 SGT 立并以 SGT 命名归档。
#   🔴 例外（-0801-01②）：**市场事件日不受本裁管**——财报日、财报后 N 交易日窗口、经济数据发布时点
#      一律按各该市场本地日历计，**援引须标市场**（如「SPGI 窗口 8-04·美东」）。
#      其由：SGT 与美东差 12–13 小时，三日以内之窗口会被算错整整一日。
export TZ=Asia/Singapore
# 热启动比 —— ADJ-0731-53① 立｜主责 CGM｜**机械可复跑：任何人任何时候得同一值**
#
# 本脚本之来由（写在这里，免得后人以为是又一个指标）：
#   `ADJ-0731-52` §一第 7 项曾令候任报「**重建阅读实耗产能占比**」，并定为甲条效果之**唯一度量**。
#   GM-9 于 -53 自纠：**该数无任何机械来源，只能由模型自估**——「本席令下任报一个他同样只能拍脑袋的数」。
#   其冲突之三条：-51⑤「凡引动态计数一律同书读取时点」／CGM 本日所立「对移动中的数只标日期不标时点即失误」／
#   GM-8 遗训「判准不是数字看起来是否合理，而是三次读数是否对得上」——**一个只能自估的数，永远凑不出三次对得上的读数**。
#
# 🔴 本改之限度（-53 自书·此处照录，不得删）：
#   **字节比测的是「须读之量」，不是「实耗之力」——二者相关但非同一。**
#   **不佯称已解决度量问题，只是把一个测不了的数换成一个测得了的数。**
#
# 用法： bash tools/warmstart-ratio.sh

set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

COMMIT=$(git log -1 --format=%H)
TS=$(date -u "+%Y-%m-%d %H:%M UTC")

# ── 本届交接书与其回执（照 gen-warmstart.sh 之同一判据·不另造一把尺）────────────
read -r HB HB_LABEL HB_RCPT < <(python3 tools/_latest-handover.py || echo "NONE NONE")
[ "$HB" = "NONE" ] && { echo "🔴 未找到任何交接书 —— 分子不完整，**中止**（不出半个比值）"; exit 3; }

echo "# 热启动比（ADJ-0731-53① · 只出数不裁定）"
echo
echo "> **读取 commit**：\`${COMMIT}\`｜**读取时点**：${TS}"
echo "> **本届交接书**：\`${HB}\`（${HB_LABEL}）｜**其回执**：\`${HB_RCPT:-🔴 尚不存在}\`"
echo

# ── 分母：复用 reading-set-size.sh 之总量，不另算一遍 ──────────────────────────
# 🔴 pattern 放宽之由（CGM 自捕·-58 收件当轮）：原为 `**合计** | **`，
#    而 -58② 改表头为「**合计（载入六项）**」→ **pattern 失配、分母取不到**。
#    **本器当时照设计 fail-closed 中止，未以旧值充数——该行为是对的，留痕于此**；
#    惟须记：**一个写死了上游表头字样的取数器，会在上游改一个字时静默失效**。
DEN=$(bash tools/reading-set-size.sh 2>/dev/null | grep -oP '\*\*合计[^|]*\*\* \| \*\*\K[0-9,]+' | tr -d ',')
if [ -z "$DEN" ]; then
  echo "🔴 分母取不到 —— **默认先疑取数坏了，不以旧值或估值充替代**；中止。"
  exit 4
fi

echo "## 分母 · 必读集全量（\`tools/reading-set-size.sh\` 之输出·同一 commit）"
echo
echo "**${DEN} B**"
echo

# ── 分子：热启动包 ＋ -52 §一第 2 步补读集 ────────────────────────────────────
echo "## 分子 · 热启动路径之须读量（-53① 所定之集·逐件列出）"
echo
echo "| 件 | 字节 | 是否在分母集内 |"
echo "|---|---:|:--|"
NUM=0; NUM_IN=0
add(){ # $1=路径 $2=是否在分母集内(Y/N)
  [ -f "$1" ] || { printf '| `%s` | — | 🔴 **不在库** |\n' "$1"; return; }
  b=$(wc -c < "$1" | tr -d ' ')
  NUM=$((NUM+b))
  [ "$2" = "Y" ] && { NUM_IN=$((NUM_IN+b)); m="✅ 在"; } || m="🔴 **不在**"
  printf '| `%s` | %s | %s |\n' "$1" "$b" "$m"
}
add docs/gm-warmstart.md            Y
add docs/constitution.md            Y
# -58② 起 CLAUDE.md 已明入载入集 → 此前「分子非分母之子集」之缺口自此闭合
add CLAUDE.md                       Y
add docs/succession/gm-succession.md Y
add "$HB"                           Y
[ -n "$HB_RCPT" ] && add "$HB_RCPT" Y || printf '| 交接书回执 | — | 🔴 **尚不存在** |\n'
# 🔴 数值序取骨架·非 ls|tail（字典序会取到上上代之骨架·CGM 自捕）
# 🔴 并留痕：本行原把注释写在同一行末尾，**注释遂吞掉其后之 add 调用**，分子少算 6,533 B——
#    而表面上分子仍是个像样的数、比值仍出得来。**又一次「输出自洽而算错」。**
SK=$(python3 -c "import sys;sys.path.insert(0,'tools');from _latest_handover import latest_skeleton;print(latest_skeleton())")
[ -n "$SK" ] && add "$SK" Y || printf '| 下一代空骨架 | — | 🔴 **尚未备** |\n'
echo "| **合计** | **${NUM}** | 其中在分母集内者 **${NUM_IN}** |"
echo

# ── 比值 ─────────────────────────────────────────────────────────────────────
python3 - "$NUM" "$NUM_IN" "$DEN" <<'PY'
import sys
num, num_in, den = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
print("## 🔴 三值并列（ADJ-0731-54③ 令·**仅报比值者不成立**）\n")
print("| 口径 | **分子 B** | **分母 B** | **比值** |")
print("|---|---:|---:|---:|")
print(f"| **热启动比**（-53① 原定） | **{num:,}** | **{den:,}** | **{num/den*100:.1f}%** |")
print(f"| **同集口径**（分子只计在分母集内者） | **{num_in:,}** | **{den:,}** | **{num_in/den*100:.1f}%** |")
print()
print(f"**节省之上界**：{100-num/den*100:.1f}%（照原定口径）")
print()
print("**🔴 分母系内生的（ADJ-0731-54③ 立·此段不得删）**：必读集全量**会随治理活动本身增长**——"
      "CGM 已自陈「本轮分母之增长部分来自本席自己之输出」。**故比值可以在负载上升时反而下降。**")
print("**一个会被自己所测之活动推动的分母，单独看比值即是自欺。** 周对账第九源须**看三条曲线，不看一条**："
      "**分子／分母／比值**——**分母上行而比值下行者，系负担加重不是减轻。**")
print()
if num_in/den > 0.95:
    print("**🔴 本比值已失去分辨力（CGM 自陈·ADJ-0731-58 收件当轮所见）**：")
    print("`ADJ-0731-58②` 把载入集重定义为六项，**而该六项恰即本比值之分子** ——")
    print("**分母收敛到了分子上，比值遂逼近 100%。**")
    print("**本比值原所量者＝「热启动路径让你少读多少必读集」；如今必读集就是热启动路径，故它已无物可量。**")
    print("**不得把这个 100% 读成「甲条大获成功」** —— 它只说明两个集合合并了，不说明继任成本降了多少。")
    print("**真正之减法读数在 `reading-set-size.sh` 之「已移出」表**（绝对字节），**不在本比值**。")
PY
echo

cat <<'NOTE'
